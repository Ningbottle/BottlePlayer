# --- Case 4: a previously staged SQLite DLL cannot hide a missing dependency ---
$sandbox4 = Join-Path $env:TEMP ("sync-verify-sqlite-" + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Force -Path $sandbox4 | Out-Null
try {
    New-DummyFile (Join-Path $sandbox4 'native\out\bottlemusic-release\EchoCAPI.dll') 'NEW-RELEASE'
    $staging = Join-Path $sandbox4 'ui\src-tauri\libs\EchoCAPI.dll'
    $profile = Join-Path $sandbox4 'ui\src-tauri\target\release\EchoCAPI.dll'
    New-DummyFile $staging 'PREVIOUS-STAGING'
    New-DummyFile $profile 'PREVIOUS-PROFILE'
    New-DummyFile (Join-Path $sandbox4 'ui\src-tauri\libs\sqlite3.dll') 'STALE-DEPENDENCY'
    $result = Invoke-SyncInSandbox -SandboxRoot $sandbox4 -Preset 'bottlemusic-release' -ExpectFailure
    Assert-True ((Get-FileText $staging) -eq 'PREVIOUS-STAGING') 'missing SQLite preserves staged EchoCAPI'
    Assert-True ((Get-FileText $profile) -eq 'PREVIOUS-PROFILE') 'missing SQLite preserves profile EchoCAPI'
    Assert-True ($result.Output -match 'Required sqlite3.dll') 'missing SQLite reports the required runtime'
}
finally {
    Remove-VerificationSandbox $sandbox4
}

# --- Case 5: a running application can lock a runtime; failure must preserve it ---
$sandbox5 = Join-Path $env:TEMP ("sync-verify-locked-" + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Force -Path $sandbox5 | Out-Null
try {
    New-DummyFile (Join-Path $sandbox5 'native\out\bottlemusic-release\EchoCAPI.dll') 'NEW-RELEASE'
    New-DummyFile (Join-Path $sandbox5 'native\vcpkg_installed\x64-windows\bin\sqlite3.dll') 'SQLITE'
    $staging = Join-Path $sandbox5 'ui\src-tauri\libs\EchoCAPI.dll'
    New-DummyFile $staging 'RUNNING-RUNTIME'
    $lock = [System.IO.File]::Open($staging, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::Read)
    try {
        $result = Invoke-SyncInSandbox -SandboxRoot $sandbox5 -Preset 'bottlemusic-release' -ExpectFailure
        Assert-True ((Get-FileText $staging) -eq 'RUNNING-RUNTIME') 'locked destination is never truncated or renamed'
        $temporaryFiles = @(Get-ChildItem -LiteralPath (Split-Path -Parent $staging) -Filter '.runtime-*.tmp')
        Assert-True ($temporaryFiles.Count -eq 0) 'failed replacement cleans its own staging file'
    }
    finally { $lock.Dispose() }
}
finally {
    Remove-VerificationSandbox $sandbox5
}

