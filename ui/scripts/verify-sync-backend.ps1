# --- Case 8: changed sources must reject an old runtime before either copy ---
$sandbox8 = Join-Path $env:TEMP ("sync-verify-stale-" + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Force -Path $sandbox8 | Out-Null
try {
    New-DummyFile (Join-Path $sandbox8 'native\out\bottlemusic-release\EchoCAPI.dll') 'STALE-RELEASE'
    New-DummyFile (Join-Path $sandbox8 'native\vcpkg_installed\x64-windows\bin\sqlite3.dll') 'SQLITE'
    $staging = Join-Path $sandbox8 'ui\src-tauri\libs\EchoCAPI.dll'
    $profile = Join-Path $sandbox8 'ui\src-tauri\target\release\EchoCAPI.dll'
    New-DummyFile $staging 'PREVIOUS-STAGING'
    New-DummyFile $profile 'PREVIOUS-PROFILE'
    $result = Invoke-SyncInSandbox -SandboxRoot $sandbox8 -Preset 'bottlemusic-release' -ExpectFailure -StaleFingerprint
    Assert-True ((Get-FileText $staging) -eq 'PREVIOUS-STAGING') 'stale fingerprint preserves staged runtime'
    Assert-True ((Get-FileText $profile) -eq 'PREVIOUS-PROFILE') 'stale fingerprint preserves profile runtime'
    Assert-True ($result.Output -match 'native_source_fingerprint_mismatch') 'stale source identity reports a rebuild requirement'
    Assert-True (@(Get-ChildItem -LiteralPath (Split-Path -Parent $staging) -Filter '.runtime-*.tmp').Count -eq 0) 'stale source identity fails before staging a replacement'
}
finally {
    Remove-VerificationSandbox $sandbox8
}

