# Pester-free contract check for sync-backend.ps1.
# Verifies preset-exact source selection, no silent fallback, and SHA-256 printing.
param([string]$SyncScript = (Join-Path $PSScriptRoot 'sync-backend.ps1'))
$ErrorActionPreference = 'Stop'

$syncScript = $SyncScript
if (-not (Test-Path -LiteralPath $syncScript)) {
    throw "sync-backend.ps1 not found next to verifier: $syncScript"
}

$failures = [System.Collections.Generic.List[string]]::new()
$checks = 0
function Assert-True {
    param([bool]$Condition, [string]$Message)
    $script:checks++
    if ($Condition) {
        Write-Host "PASS: $Message"
    } else {
        $script:failures.Add($Message) | Out-Null
        Write-Host "FAIL: $Message"
    }
}

. (Join-Path $PSScriptRoot 'backend-preset.ps1')
Assert-True ((Resolve-BackendPreset -DebugFlag 'true') -eq 'bottlemusic-check') 'explicit debug flag selects native Debug'
Assert-True ((Resolve-BackendPreset -DebugFlag 'false') -eq 'bottlemusic-release') 'explicit production flag selects native Release'
Assert-True ((Resolve-BackendPreset) -eq 'bottlemusic-check') 'manual backend build defaults to Debug'
Assert-True ((Resolve-BackendPreset -RequestedPreset 'bottlemusic-release' -DebugFlag 'true') -eq 'bottlemusic-release') 'explicit native preset takes priority'
$invalidDebugFlag = $false
try { Resolve-BackendPreset -DebugFlag 'unexpected' | Out-Null }
catch { $invalidDebugFlag = $true }
Assert-True $invalidDebugFlag 'unrecognized Tauri profile fails before building'

$uiRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$tauriConfig = [System.IO.File]::ReadAllText(
    (Join-Path $uiRoot 'src-tauri\tauri.conf.json'),
    [System.Text.Encoding]::UTF8
) | ConvertFrom-Json
$packageConfig = [System.IO.File]::ReadAllText(
    (Join-Path $uiRoot 'package.json'),
